LifeTreeNode? lifeTreeNode(LifeSkillKind k, String id) => _byId[k]![id];

/// Node ids of [k] (save migration drops everything else).
bool isLifeTreeNode(LifeSkillKind k, String id) => _byId[k]!.containsKey(id);
